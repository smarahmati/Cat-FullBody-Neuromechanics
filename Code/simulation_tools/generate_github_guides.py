"""Create readable GitHub Markdown companions for the local HTML guides.

Run from any directory with Python's standard library using the included equation
figures. Building new or changed figures also requires the optional Node/MathJax
renderer described in Documentation/publishing.md. Scientific text, tables,
citations and images come from the HTML documentation. Numbered equations use
Documentation/equations.json, the same equation source as the methods guide.
No simulation input, parameter, numerical result or repository visibility changes.

Folder index.html pages become README.md. Other guides keep their name with a
.md extension. Large tables are divided into linked pages below GitHub's display
limit. Python links open actual source files. Interactive controls remain in the
downloaded HTML; their Markdown companions provide figures and data links.
"""

from html.parser import HTMLParser
from pathlib import Path, PurePosixPath
from urllib.parse import quote, unquote, urlsplit
import html
import json
import posixpath
import re
import subprocess
import unicodedata
from render_documentation_equations import EquationFigures

ROOT = Path(__file__).resolve().parents[2]
MARKER = '<!-- Generated by Code/simulation_tools/generate_github_guides.py -->'
VOID_TAGS = {'area', 'base', 'br', 'col', 'embed', 'hr', 'img', 'input',
             'link', 'meta', 'param', 'source', 'track', 'wbr', 'mspace'}
SITE_PREFIX = 'https://smarahmati.github.io/Cat-FullBody-Neuromechanics/'
FIGURES = EquationFigures()


class Element:
    """A small HTML tree node; strings in children contain decoded text."""

    def __init__(self, tag, attrs=()):
        self.tag = tag
        self.attrs = dict(attrs)
        self.children = []

    def find_all(self, tag):
        found = [self] if self.tag == tag else []
        for child in self.children:
            if isinstance(child, Element):
                found.extend(child.find_all(tag))
        return found

    def text(self):
        return ''.join(c.text() if isinstance(c, Element) else c for c in self.children)


class Document(HTMLParser):
    """Read HTML without loading scripts, remote assets or optional packages."""

    def __init__(self, source):
        super().__init__(convert_charrefs=True)
        self.root = Element('document')
        self.stack = [self.root]
        self.feed(source)
        self.close()

    def handle_starttag(self, tag, attrs):
        node = Element(tag, attrs)
        self.stack[-1].children.append(node)
        if tag not in VOID_TAGS:
            self.stack.append(node)

    def handle_startendtag(self, tag, attrs):
        self.stack[-1].children.append(Element(tag, attrs))

    def handle_endtag(self, tag):
        for index in range(len(self.stack) - 1, 0, -1):
            if self.stack[index].tag == tag:
                del self.stack[index:]
                break

    def handle_data(self, data):
        self.stack[-1].children.append(data)


def public_files():
    """Respect Git's ignore rules, including private papers and local meshes."""
    names = subprocess.check_output(
        ['git', '-C', str(ROOT), 'ls-files', '--cached', '--others',
         '--exclude-standard', '-z']).decode('utf-8').split('\0')
    return sorted({n for n in names if n and (ROOT / n).is_file()})


def markdown_destination(source):
    """Use folder READMEs and link source-code listings to their real scripts."""
    if source in {'index.html', 'START_HERE.html'}:
        return 'README.md'
    if source.startswith('Documentation/Code_Reference/') and source.endswith('.py.html'):
        return PurePosixPath(source).name[:-5].replace('__', '/')
    if source == 'Simulation_Results/Intact_Walking/APPLIED_PARAMETERS.html':
        return 'Simulation_Results/Intact_Walking/applied_parameters.md'
    path = PurePosixPath(source)
    if path.name == 'index.html':
        return str(path.with_name('README.md'))
    return str(path.with_suffix('.md')) if path.suffix == '.html' else source


def relative_link(page, target):
    """Encode spaces but retain portable repository-relative paths."""
    return quote(posixpath.relpath(target, posixpath.dirname(page) or '.'), safe='/#')


def mathml_latex(node):
    """Convert the few unnumbered MathML formulas without flattening fractions."""
    if isinstance(node, str):
        return node.strip()
    children = [c for c in node.children if isinstance(c, Element)]
    parts = [mathml_latex(c) for c in children]
    text = unicodedata.normalize('NFKC', node.text().strip())
    symbols = {'−': '-', '×': r'\times ', '≤': r'\leq ', '≥': r'\geq ',
               'α': r'\alpha ', 'β': r'\beta ', 'λ': r'\lambda ',
               'ν': r'\nu ', 'τ': r'\tau ', 'ξ': r'\xi ',
               'Δ': r'\Delta ', '∂': r'\partial ', '∞': r'\infty ',
               '{': r'\{', '}': r'\}', '∑': r'\sum ', 'ε': r'\epsilon ',
               '≃': r'\simeq ', '·': r'\cdot ', '‖': r'\Vert '}
    if node.tag in {'mi', 'mo', 'mn', 'mtext'}:
        if text in symbols:
            return symbols[text]
        if text in {'max', 'min', 'exp', 'cos', 'sin', 'tanh', 'log'}:
            return '\\' + text + ' '
        if len(text) > 1 and node.tag == 'mi':
            return r'\mathrm{' + text + '}'
        return text
    if node.tag == 'mfrac':
        return r'\frac{' + parts[0] + '}{' + parts[1] + '}'
    if node.tag == 'msub':
        return '{' + parts[0] + '}_{' + parts[1] + '}'
    if node.tag == 'msup':
        return '{' + parts[0] + '}^{' + parts[1] + '}'
    if node.tag == 'msubsup':
        return '{' + parts[0] + '}_{' + parts[1] + '}^{' + parts[2] + '}'
    if node.tag == 'mover':
        return r'\dot{' + parts[0] + '}' if children[1].text() in {'˙', '̇'} else r'\overline{' + parts[0] + '}'
    if node.tag == 'msqrt':
        return r'\sqrt{' + ''.join(parts) + '}'
    if node.tag == 'mspace':
        return r'\,'
    if node.tag == 'mtable':
        return r'\begin{matrix}' + r' \\ '.join(parts) + r'\end{matrix}'
    if node.tag == 'mtr':
        return ' & '.join(parts)
    return ''.join(parts)


class MarkdownGuide:
    """Convert one guide and collect any separately paginated parameter tables."""

    def __init__(self, source, html_sources):
        self.source = source
        self.destination = markdown_destination(source)
        self.html_sources = html_sources
        self.tree = Document((ROOT / source).read_text(encoding='utf-8')).root
        self.tables = {}
        self.table_number = 0
        self.heading = 'Table'
        self.formula_number = 0
        equations = json.loads((ROOT / 'Documentation/equations.json').read_text(encoding='utf-8'))
        self.equations = {str(e['number']): e['latex'] for e in equations}
        self.equation_labels = {str(e['number']): e['label'] for e in equations}

    def equation_figure(self, latex, number=None, inline=False):
        """Embed outlined mathematics that GitHub can display as ordinary images."""
        if number is not None:
            label = self.equation_labels[number]
            key = 'method_' + str(number).zfill(2) + '_' + label
        else:
            self.formula_number += 1
            label = self.heading
            # Identical attachment formulas are shared by all snapshot guides.
            key = PurePosixPath(self.source).stem + '_' + str(self.formula_number).zfill(2)
        target = FIGURES.register(latex, label, key, number, inline)
        image = '![' + ('Equation ' + str(number) + ': ' if number else '')
        image += label.replace('[', '').replace(']', '') + ']('
        image += relative_link(self.destination, target) + ')'
        return image if inline else '\n\n' + image + '\n\n'

    def link(self, address):
        """Map guide-to-guide links to Markdown while leaving downloads intact."""
        if address.startswith(SITE_PREFIX):
            address = '/' + address[len(SITE_PREFIX):]
        parsed = urlsplit(html.unescape(address))
        if parsed.scheme or parsed.netloc:
            return address
        if not parsed.path:
            return '#' + parsed.fragment if parsed.fragment else ''
        path = unquote(parsed.path)
        target = (path.lstrip('/') if path.startswith('/') else
                  posixpath.normpath(posixpath.join(posixpath.dirname(self.source), path)))
        if (ROOT / target).is_dir() and target.rstrip('/') + '/index.html' in self.html_sources:
            target = target.rstrip('/') + '/index.html'
        if target in self.html_sources:
            target = markdown_destination(target)
        result = relative_link(self.destination, target)
        if parsed.fragment:
            result += '#' + parsed.fragment
        return result

    def render_children(self, node):
        return ''.join(self.render(child) for child in node.children)

    def table(self, node):
        """Keep headers on each page and preserve every row of large tables."""
        self.table_number += 1
        rows = []
        for row in node.find_all('tr'):
            cells = [c for c in row.children if isinstance(c, Element) and c.tag in {'th', 'td'}]
            if cells:
                rows.append([re.sub(r'\s+', ' ', self.render_children(c)).strip().replace('|', '&#124;') for c in cells])
        if not rows:
            return ''
        width = max(len(r) for r in rows)
        rows = [r + [''] * (width - len(r)) for r in rows]
        header = '| ' + ' | '.join(rows[0]) + ' |\n| ' + ' | '.join(['---'] * width) + ' |\n'
        lines = ['| ' + ' | '.join(r) + ' |\n' for r in rows[1:]]
        parameter_table = self.source == 'Documentation/parameter_tables.html'
        if parameter_table or width > 5:
            # Wide scientific tables exceed GitHub's content column. Each record
            # retains every source field in a narrow, expandable two-column table.
            records = []
            for row in rows[1:]:
                identity = row[0] + (' · ' + row[1] if parameter_table else '')
                summary = html.escape(identity.replace('`', ''))
                record = '<details>\n<summary>' + summary + '</summary>\n\n'
                record += '| Field | Value |\n| --- | --- |\n'
                record += ''.join('| ' + field + ' | ' + value + ' |\n'
                                  for field, value in zip(rows[0], row))
                records.append(record + '\n</details>\n\n')
            header = ('Each entry contains its values, units, meaning and source information. '
                      'Select an entry to read all fields.\n\n')
            lines = records
        if not parameter_table and len(lines) <= 200 and len(''.join(lines).encode('utf-8')) < 220000:
            return '\n\n' + header + ''.join(lines) + '\n'
        slug = re.sub(r'[^a-z0-9]+', '_', self.heading.lower()).strip('_')
        # The HTML summary often contains the entry count; filenames use the category.
        slug = re.sub(r'_\d+_entries$', '', slug) or f'table_{self.table_number}'
        directory = ('Documentation/Parameter_Tables' if parameter_table else
                     str(PurePosixPath(self.destination).with_suffix('')) + '_tables')
        links = []
        for offset in range(0, len(lines), 200):
            last = min(offset + 200, len(lines))
            name = f'{directory}/{slug}_entries_{offset + 1}_to_{last}.md'
            title = f'{self.heading} — entries {offset + 1}–{last}'
            self.tables[name] = (MARKER + '\n\n# ' + title + '\n\n'
                '[Back to parameter guide](' + relative_link(name, self.destination) + ')\n\n'
                + header + ''.join(lines[offset:last]))
            links.append(f'- [{title}]({relative_link(self.destination, name)})')
        return '\n\n' + '\n'.join(links) + '\n\n'

    def render(self, node):
        if isinstance(node, str):
            return re.sub(r'\s+', ' ', node)
        tag = node.tag
        if tag in {'script', 'style', 'head', 'header', 'footer', 'nav', 'button', 'select', 'input', 'label'}:
            return ''
        anchor = ('\n\n<a name="' + html.escape(node.attrs['id'], quote=True) + '"></a>\n\n'
                  if node.attrs.get('id') and tag not in {'math', 'svg', 'table'} else '')
        if tag == 'div' and 'eq' in node.attrs.get('class', '').split():
            numbers = [e.text().strip('() ') for e in node.find_all('span') if e.attrs.get('class') == 'num']
            if numbers and numbers[0] in self.equations:
                return self.equation_figure(self.equations[numbers[0]], numbers[0])
        if tag == 'math':
            equation = mathml_latex(node)
            return self.equation_figure(equation, inline=len(equation) < 40)
        if tag in {'h1', 'h2', 'h3', 'h4', 'h5', 'h6', 'summary'}:
            self.heading = node.text().strip()
            level = int(tag[1]) if tag != 'summary' else 3
            return anchor + '\n\n' + '#' * level + ' ' + self.render_children(node).strip() + '\n\n'
        if tag == 'table':
            return self.table(node)
        if tag == 'pre':
            text = node.text().strip('\n')
            return '\n\n```\n' + text + '\n```\n\n'
        if tag == 'code':
            return '`' + node.text().strip() + '`'
        if tag in {'b', 'strong'}:
            return '**' + self.render_children(node).strip() + '**'
        if tag in {'em', 'i'}:
            return '*' + self.render_children(node).strip() + '*'
        if tag == 'a':
            body = self.render_children(node).strip()
            return anchor + ('[' + body + '](' + self.link(node.attrs['href']) + ')' if node.attrs.get('href') else body)
        if tag == 'img':
            alt = node.attrs.get('alt', 'Model figure').replace('[', '').replace(']', '')
            return '\n\n![' + alt + '](' + self.link(node.attrs['src']) + ')\n\n'
        if tag in {'video', 'object'}:
            address = node.attrs.get('src') or node.attrs.get('data')
            sources = node.find_all('source')
            if not address and sources:
                address = sources[0].attrs.get('src')
            return '\n\n[Open or download the simulation video](' + self.link(address) + ')\n\n' if address else ''
        if tag == 'svg':
            image = relative_link(self.destination, 'Documentation/Figures_and_Videos/model_flowchart.svg')
            return '\n\n![Neuromechanical process](' + image + ')\n\n'
        if tag in {'ul', 'ol'}:
            items = []
            for item in node.children:
                if isinstance(item, Element) and item.tag == 'li':
                    prefix = f'{len(items) + 1}. ' if tag == 'ol' else '- '
                    value = self.render_children(item).strip().replace('\n', '\n  ')
                    items.append(prefix + value)
            return '\n\n' + '\n'.join(items) + '\n\n'
        if tag == 'br':
            return '<br>'
        body = self.render_children(node)
        if tag in {'p', 'div', 'section', 'article', 'figure', 'figcaption', 'details'}:
            return anchor + '\n\n' + body.strip() + '\n\n'
        return anchor + body

    def write(self):
        titles = self.tree.find_all('h1') or self.tree.find_all('title')
        title = titles[0].text().strip() if titles else PurePosixPath(self.source).parent.name.replace('_', ' ')
        nodes = self.tree.find_all('main') or self.tree.find_all('body') or [self.tree]
        body = self.render_children(nodes[0])
        body = re.sub(r'\n[ \t]+\n', '\n\n', body)
        body = re.sub(r'(?m)^# ' + re.escape(title) + r'\s*$', '', body)
        body = re.sub(r'\n{3,}', '\n\n', body).strip()
        home = relative_link(self.destination, 'README.md')
        folders = relative_link(self.destination, 'Documentation/project_structure.md')
        text = MARKER + '\n\n# ' + title + '\n\n[Project home](' + home + ') · [Folder guide](' + folders + ')\n\n' + body + '\n'
        if self.source == 'Documentation/code_flowchart.html':
            text = text.replace('Each box opens a numbered source view.', 'The numbered links above open the actual Python source on GitHub; diagram boxes are clickable in the downloaded HTML.')
        if self.source == 'Documentation/muscle_model.html':
            text = text.replace('Inspect every parameter for one muscle', 'Inspect the parameters of every muscle')
            start = text.index('## Inspect the parameters of every muscle')
            end = text.index('## Shared curve constants', start)
            text = (text[:start] + '## Inspect the parameters of every muscle\n\n'
                    'Use the [complete parameter tables](parameter_tables.md) for units, source values '
                    'and applied values, or inspect the [per-muscle data](muscle_model_parameters.json). '
                    'The [attachment map](../Data/Model_Parameters/ATTACHMENT_MAP.md) gives origins, '
                    'insertions and routing. Edit the linked configuration files and start a new '
                    'simulation to apply changes. The downloaded HTML also provides a muscle selector.\n\n'
                    + text[end:])
        (ROOT / self.destination).write_text(text, encoding='utf-8')
        for path, content in self.tables.items():
            (ROOT / path).parent.mkdir(parents=True, exist_ok=True)
            (ROOT / path).write_text(content.rstrip() + '\n', encoding='utf-8')
        return [self.destination, *self.tables]


