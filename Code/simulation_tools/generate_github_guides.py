def generate_guides():
    """Update Markdown companions; retain the independently useful local HTML."""
    files = public_files()
    sources = {name for name in files if name.endswith('.html')
               and ('Simulation_Code_Used/' not in name or name.endswith('/index.html'))}
    written = []
    for source in sorted(sources):
        if source in {'index.html', 'START_HERE.html'} or source.startswith('Documentation/Code_Reference/'):
            continue
        if source.endswith('/interactive_experimental_comparison.html'):
            written.append(write_interactive_alternative())
        elif source.endswith('/APPLIED_PARAMETERS.html'):
            written.append(write_applied_parameter_guide())
        else:
            written.extend(MarkdownGuide(source, sources).write())
    # A source index is useful, but duplicating every Python file as Markdown is not.
    source_index = ROOT / 'Documentation/Code_Reference/README.md'
    source_index.write_text(MARKER + '\n\n# Python source code\n\n'
        '[Subsystem functions](../../Code/neuromechanics/README.md) · '
        '[Code flowchart](../code_flowchart.md) · [Simulation tools](../../Code/simulation_tools/README.md)\n\n'
        'The GitHub guides link directly to Python files. The HTML pages in this folder '
        'provide numbered source listings when reading the downloaded documentation.\n', encoding='utf-8')
    written.append(source_index.relative_to(ROOT).as_posix())
    parameter_index = ROOT / 'Documentation/Parameter_Tables/README.md'
    parameter_index.write_text(MARKER + '\n\n# Model parameter tables\n\n'
        '[Table of contents and column definitions](../parameter_tables.md)\n\n'
        'Tables are divided by physical subsystem and entry range. Every entry keeps '
        'its units, source value, applied value and scientific explanation.\n', encoding='utf-8')
    written.append(parameter_index.relative_to(ROOT).as_posix())
    # The root README is hand-maintained; retain its mathematical source in the
    # figure catalog while converting display formulas to the same stable format.
    readme_path = ROOT / 'README.md'
    readme = readme_path.read_text(encoding='utf-8')
    FIGURES.preserve_readme_figures(readme)
    readme_count = 0
    def readme_equation(match):
        nonlocal readme_count
        readme_count += 1
        key = 'readme_' + str(readme_count).zfill(2)
        labels = ['Activation and muscle–tendon length', 'Tendon force and muscle moments',
                  'Coupled multibody dynamics']
        target = FIGURES.register(match.group(1).strip(), labels[readme_count-1], key)
        return '![' + labels[readme_count-1] + '](' + target + ')'
    readme = re.sub(r'\$\$(.*?)\$\$', readme_equation, readme, flags=re.S)
    # Short glossary symbols need only ordinary text and subscript formatting.
    glossary = {'u':'u', 'a':'a', r'\tau':'τ', 'L_{MT}':'L<sub>MT</sub>',
                'l_f':'l<sub>f</sub>', 'l_T':'l<sub>T</sub>', 'l_s':'l<sub>s</sub>',
                r'\alpha':'α', 'F_0':'F<sub>0</sub>', 'q':'q', 'M':'M', 'b':'b',
                'Q':'Q', 'J_c^TF_c':'J<sub>c</sub><sup>T</sup>F<sub>c</sub>'}
    for source, formatted in glossary.items():
        readme = readme.replace('$' + source + '$', formatted)
    readme_path.write_text(readme, encoding='utf-8')
    FIGURES.write()
    too_large = [name for name in written if (ROOT / name).stat().st_size >= 450000]
    if too_large:
        raise ValueError('Split these guides before publishing: ' + ', '.join(too_large))
    print(f'Wrote {len(written)} GitHub Markdown guides; model and results unchanged.')
    return written


if __name__ == '__main__':
    generate_guides()
